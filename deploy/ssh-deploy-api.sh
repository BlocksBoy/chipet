#!/usr/bin/env bash
# 上传源码到弗吉尼亚，在服务器上构建 chipet-api 镜像并重启 api + Caddy。
# 密钥来自本地 server/.env（勿提交）；远程落在 $DEPLOY_PATH/.env.api。
# 不依赖本机 Docker。
#
#   ./deploy/ssh-deploy-api.sh
set -euo pipefail

_SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$_SCRIPT_DIR/.." && pwd)"

if [[ -f "$_SCRIPT_DIR/.env.deploy.local" ]]; then
  set +u
  # shellcheck disable=SC1091
  source "$_SCRIPT_DIR/.env.deploy.local"
  set -u
fi

if [[ -n "${SSH_IDENTITY:-}" ]] && [[ "${SSH_IDENTITY:0:1}" == '~' ]]; then
  SSH_IDENTITY="${SSH_IDENTITY/#\~/${HOME}}"
fi

SERVER_USER="${SERVER_USER:?请设置 SERVER_USER}"
SERVER_HOST="${SERVER_HOST:?请设置 SERVER_HOST}"
SERVER_PORT="${SERVER_PORT:-22}"
DEPLOY_PATH="${DEPLOY_PATH:-/home/ubuntu/chipet}"
SITE_DOMAIN="${SITE_DOMAIN:-chipet.web3book.io}"
CADDY_HTTPS_PORT="${CADDY_HTTPS_PORT:-8443}"
REMOTE_SRC="${REMOTE_SRC:-/tmp/chipet-api-src.tgz}"

SERVER_ENV="$REPO_ROOT/server/.env"
[[ -f "$SERVER_ENV" ]] || { echo "错误: 缺少 $SERVER_ENV（需 AI_API_KEY / AI_BASE_URL / AI_MODEL）" >&2; exit 1; }
grep -q '^AI_API_KEY=.\+' "$SERVER_ENV" || { echo "错误: server/.env 未设置 AI_API_KEY" >&2; exit 1; }
[[ -f "$REPO_ROOT/package-lock.json" ]] || { echo "错误: 缺少 package-lock.json" >&2; exit 1; }

SSH_CMD=(ssh -p "$SERVER_PORT")
SCP_CMD=(scp -P "$SERVER_PORT")
if [[ -n "${SSH_IDENTITY:-}" ]]; then
  SSH_CMD+=(-i "$SSH_IDENTITY")
  SCP_CMD+=(-i "$SSH_IDENTITY")
fi
SSH_CMD+=("$SERVER_USER@$SERVER_HOST")

echo ">>> 打包 API 构建上下文 …"
SRC_TAR=$(mktemp /tmp/chipet-api-src.XXXXXX.tgz)
trap 'rm -f "$SRC_TAR"' EXIT
(
  cd "$REPO_ROOT"
  COPYFILE_DISABLE=1 tar --no-xattrs --no-mac-metadata -czf "$SRC_TAR" \
    --exclude=.DS_Store \
    --exclude='**/node_modules' \
    --exclude='**/.env' \
    --exclude='**/dist' \
    package.json package-lock.json \
    packages \
    server \
    deploy/Dockerfile.api
)

echo ">>> 上传源码 / compose / Caddyfile / AI env → $SERVER_USER@$SERVER_HOST"
"${SSH_CMD[@]}" "mkdir -p $DEPLOY_PATH"
"${SCP_CMD[@]}" "$SRC_TAR" "$SERVER_USER@$SERVER_HOST:$REMOTE_SRC"
"${SCP_CMD[@]}" "$_SCRIPT_DIR/Caddyfile" "$_SCRIPT_DIR/docker-compose.yml" \
  "$SERVER_USER@$SERVER_HOST:$DEPLOY_PATH/"
{
  echo "# generated by ssh-deploy-api.sh — do not commit"
  grep -E '^(AI_BASE_URL|AI_API_KEY|AI_MODEL|PORT|CHAIN_ID|RPC_URL)=' "$SERVER_ENV" || true
  echo "PORT=8787"
} | "${SSH_CMD[@]}" "cat > $DEPLOY_PATH/.env.api && chmod 600 $DEPLOY_PATH/.env.api"

"${SSH_CMD[@]}" "printf '%s\n' 'SITE_DOMAIN=$SITE_DOMAIN' 'CADDY_HTTPS_PORT=$CADDY_HTTPS_PORT' > $DEPLOY_PATH/.env.deploy"

Q_PATH=$(printf %q "$DEPLOY_PATH")
Q_SRC=$(printf %q "$REMOTE_SRC")

echo ">>> 远程构建镜像并重启 api + caddy …"
"${SSH_CMD[@]}" bash -s <<REMOTE
set -euo pipefail
DEPLOY_PATH=$Q_PATH
SRC=$Q_SRC
if docker info >/dev/null 2>&1; then DC=(docker compose); DOCKER=(docker); else DC=(sudo docker compose); DOCKER=(sudo docker); fi

BUILD_DIR=\$(mktemp -d /tmp/chipet-api-build.XXXXXX)
trap 'rm -rf "\$BUILD_DIR"' EXIT
tar -xzf "\$SRC" -C "\$BUILD_DIR"
rm -f "\$SRC"

"\${DOCKER[@]}" build -f "\$BUILD_DIR/deploy/Dockerfile.api" -t chipet-api:latest "\$BUILD_DIR"

cd "\$DEPLOY_PATH"
"\${DC[@]}" --env-file .env.deploy -f docker-compose.yml up -d --force-recreate api caddy
"\${DC[@]}" --env-file .env.deploy -f docker-compose.yml ps
sleep 3
API_CID=\$("\${DC[@]}" --env-file .env.deploy -f docker-compose.yml ps -q api)
"\${DOCKER[@]}" exec "\$API_CID" node -e "fetch('http://127.0.0.1:8787/api/health').then(r=>r.json()).then(j=>{console.log(JSON.stringify(j)); if(!j.ai) process.exit(2)})"
REMOTE

echo ">>> 完成。公开检查: https://$SITE_DOMAIN/api/health （需 Cloudflare → ${CADDY_HTTPS_PORT}）"
